import pandas as pd
# 数据集中只包含三种格式：斜线 / 中文 / 点号
data_simple = {
'评论ID': list(range(1, 11)),
'评论者': [f'用户{i}' for i in range(1, 11)],
'评分': [5, 4, 3, 2, 5, 1, 4, 2, 5, 3],
'电影评论': [
"很好看", "剧情不错", "不推荐", "推荐", "特效炸裂",
"演技差", "演技在线", "情节紧凑", "音乐动听", "节奏慢"
],
'评论时间': [
"2024/01/01", 
"2024年01月02日",
"2024.01.03", 
"2024/01/04",
"2024年01月05日",
"2024.01.06",
"2024/01/07",
"2024年01月08日",
"2024.01.09",
"2024/01/10"
]
}
# 创建 DataFrame
df = pd.DataFrame(data_simple)

# 清洗函数（只用字符串方法，不用 re）
def clean_time_str(s):
    s = s.replace("年", "-").replace("月", "-").replace("日", "")
    s = s.replace("/", "-").replace(".", "-")
    return s.strip()

# 修改【4】处代码清洗并转换
df['评论时间_清洗后'] = df['评论时间'].apply(clean_time_str)
df['评论时间_标准格式'] =pd.to_datetime(df['评论时间_清洗后'], errors='coerce').dt.strftime('%Y-%m-%d') 

print("\n 修正时间格式后的表格：")
print(df[['评论ID', '评论时间', '评论时间_清洗后', '评论时间_标准格式']])
